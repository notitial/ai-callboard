import { expect, mock, test } from 'claude-code/testing'
import { fake, MIN, T0 } from './fake'

// The engine beneath the plugin, answered by the in-memory fake: what the adapters call on `$` reaches the same fs, processes, state and session the engine specs use.
function engine(on: any, f: ReturnType<typeof fake>) {
  const clock = mock.clock(on, { now: T0 })
  on('session.start', (_: any, e: any) => ({ cwd: e.cwd }))
  on('session.id', () => ({ value: f.h.sid }))
  on('session.root', () => ({ value: f.h.root }))
  on('session.usage', async () => ({ value: await f.$.session.usage() }))
  on('env.get', async (_: any, e: any) => ({ value: await f.$.env.get(e.name) }))
  on('fs.read', async (_: any, e: any) => ({ value: await f.$.fs.read(e.path, e.init ?? e.options) }))
  on('fs.write', async (_: any, e: any) => ({ value: await f.$.fs.write(e.path, e.text ?? e.data) }))
  on('fs.list', async (_: any, e: any) => ({ value: await f.$.fs.list(e.path) }))
  on('fs.stat', async (_: any, e: any) => ({ value: await f.$.fs.stat(e.path) }))
  on('fs.exists', async (_: any, e: any) => ({ value: await f.$.fs.exists(e.path) }))
  on('process.run', async (_: any, e: any) => ({ value: await f.$.process.run(e.argv, e.init) }))
  on('state.get', async (_: any, e: any) => ({ value: await f.$.state.get({ key: e.key }) }))
  on('state.set', async (_: any, e: any) => ({ value: await f.$.state.set({ key: e.key }, e.value, { ifVersion: e.ifVersion }) }))
  on('prompt.read', () => ({ value: { text: f.h.draft, cursor: 0 } }))
  on('prompt.submit', (_: any, e: any) => (f.h.submitted.push(e.text), { text: e.text }))
  on('ui.toast', async (_: any, e: any) => ({ value: await f.$.ui.toast(e.text) }))
  on('turn.complete', (_: any, e: any) => ({ text: e.answer }))
  on('turn.start', (_: any, e: any) => ({ turnId: e.turnId }))
  on('agent.list', () => ({ value: [] }))
  on('command.register', (_: any, e: any) => (f.h.commands.push(e.name), { value: { command: e.name } }))
  on('tool.register', (_: any, e: any) => (f.h.tools.push(e.name), { value: { tool: e.name } }))
  on('command.run', (_: any, e: any) => (f.h.compactRuns.push(`${e.command} ${e.args}`), { value: { text: '' } }))
  return clock
}
const start = ($: any) => $.session.start({ cwd: '/', surface: 'terminal', isInteractive: true })
const own = (f: ReturnType<typeof fake>) => f.seed({ sid: 'sid-me', pid: 10, name: 'me', cwd: '/w/me', kind: 'interactive' })

test('a session starts with the five tools every session has and the three commands; a lead row adds the fourteen at the next tick', async ($, on) => {
  const f = fake()
  own(f)
  const clock = engine(on, f)
  await start($)
  expect(f.h.tools.sort()).toEqual(['go_request', 'go_status', 'pr_watch', 'request_compact', 'rest'])
  expect(f.h.commands.sort()).toEqual(['callboard', 'rest', 'unattended'])
  f.table({ 'sid-me': { name: 'me', folder: '/w/me', lead: { repos: [] } } })
  await clock.advance(12_000)
  expect(f.h.tools.length).toBe(19)
  expect(f.h.tools).toContain('lane_list')
})
test('only his typed turn runs a form that widens what a session may do; the engine-stamped origin decides', async ($, on) => {
  const f = fake()
  own(f)
  engine(on, f)
  await start($)
  const off = (kind?: string) => $.command.run({ command: 'callboard', args: 'off', ...(kind === undefined ? {} : { origin: { kind } }) } as any)
  for (const kind of ['plugin', 'sdk', 'peer', 'task-notification', undefined]) expect((await off(kind)).text).toContain('only when the person types it themselves')
  expect(f.h.files.get('/Users/x/.claude/callboard/v2/sessions.json')).toBeUndefined()
  expect((await off('composer')).text).toContain('Callboard is off for this session')
  expect((await $.command.run({ command: 'callboard', args: 'on', origin: { kind: 'bridge' } } as any)).text).toContain('Callboard is on for this session')
  expect((await $.command.run({ command: 'rest', args: '', origin: { kind: 'plugin' } } as any)).text).toContain('Rest set')
})
test('the keepalive: at the configured 30 minutes after a turn ends, one ping is submitted, and not another in the same gap', async ($, on) => {
  const f = fake()
  own(f)
  const clock = engine(on, f)
  f.h.files.set('/Users/x/.claude/callboard/v2/config.json', JSON.stringify({ keepalive: true, pingAfterMin: 30, stopAfterH: 2, idleK: 300, workingK: 400 }))
  await start($)
  await $.turn.complete({ answer: 'ok', durationMs: 1, isAborted: false, turnId: 't1', reason: 'answer' } as any)
  await clock.advance(31 * MIN)
  expect(f.h.submitted.filter((t) => t.includes('keepalive:')).length).toBe(1)
  await clock.advance(10 * MIN)
  expect(f.h.submitted.filter((t) => t.includes('keepalive:')).length).toBe(1)
})
test('a tool with no body yet refuses not-built, whatever the caller', async ($, on) => {
  const f = fake()
  own(f)
  engine(on, f)
  await start($)
  for (const name of ['lane_list', 'lane_open']) expect((await $.tool.call({ tool: `mcp__callboard__${name}` } as any)).deny).toBe('callboard: not-built')
})
test('the ask tools are wired: a lead\'s prompt_list answers and go_status says the guard is missing', async ($, on) => {
  const f = fake()
  own(f)
  f.table({ 'sid-me': { name: 'me', folder: '/w/me', lead: { repos: [] } } })
  engine(on, f)
  await start($)
  expect((await $.tool.call({ tool: 'mcp__callboard__prompt_list' } as any)).result).toContain('No asks are waiting')
  expect((await $.tool.call({ tool: 'mcp__callboard__go_status' } as any)).result).toContain('guard')
})
